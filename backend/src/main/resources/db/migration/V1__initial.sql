CREATE TABLE notes (
id VARCHAR(36) PRIMARY KEY,
owner_id VARCHAR(100) NOT NULL,
title VARCHAR(300) NOT NULL,
content CLOB NOT NULL,
space VARCHAR(20) NOT NULL,
category VARCHAR(80) NOT NULL,
tags VARCHAR(1000) NOT NULL,
favorite BOOLEAN NOT NULL DEFAULT FALSE,
published BOOLEAN NOT NULL DEFAULT FALSE,
draft BOOLEAN NOT NULL DEFAULT TRUE,
share_id VARCHAR(36) NOT NULL UNIQUE,
entry_date DATE NOT NULL,
created_at TIMESTAMP NOT NULL,
updated_at TIMESTAMP NOT NULL,
version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX notes_owner_updated ON notes(owner_id,updated_at);
CREATE TABLE attachments (
id VARCHAR(36) PRIMARY KEY,
note_id VARCHAR(36) NOT NULL REFERENCES notes(id) ON DELETE CASCADE,
filename VARCHAR(255) NOT NULL,
media_type VARCHAR(100) NOT NULL,
byte_size BIGINT NOT NULL,
storage_key VARCHAR(36) NOT NULL
);
